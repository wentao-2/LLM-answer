"""Render the main numerical tables from retained, unrounded CSV exports.

No scientific aggregation or inference is performed. Run from any directory.
"""
from pathlib import Path
import csv
import itertools
import json
import math

ROOT = Path(__file__).resolve().parents[1]


def read(name):
    with (ROOT / name).open(encoding='utf-8-sig', newline='') as handle:
        return list(csv.DictReader(handle))


def number(value):
    """Keep four decimals for large effects and two significant small digits."""
    value = float(value)
    assert math.isfinite(value)
    if value == 0:
        return '$0$'
    if abs(value) < .001:
        mantissa, exponent = f'{value:.1e}'.split('e')
        return '$' + mantissa + r'\times10^{' + str(int(exponent)) + '}$'
    return f'${value:.4f}$'


def row(values):
    return ' & '.join(values) + r' \\'


def write(name, lines):
    (ROOT / 'sections' / name).write_text('\n'.join(lines) + '\n', encoding='utf-8')


def main():
    all_static = read('data/full_results/attribution_decomposition.csv')
    static = [r for r in all_static if all(r[k] == v for k, v in {
        'model': 'qwen3-8b-thinking', 'protocol': 'independent',
        'visibility': 'signal_visible', 'relation': 'agree'}.items())]
    assert len(static) == 8
    static.sort(key=lambda r: (r['reminder'], r['output_instruction'], r['template_id']))
    keys = ('self_directional_error', 'other_directional_error', 'attribution_gap', 'self_mae', 'other_mae')
    lines = [r'% Generated by scripts/build_main_results.py from retained CSVs.',
        r'\begin{table*}[t]', r'\centering', r'{\small\setlength{\tabcolsep}{4pt}',
        r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}llrrrrrr@{}}',
        r'\toprule', r'\multicolumn{8}{l}{\textbf{A. Static attribution: independent agreeing readings, $S$ visible}} \\',
        r'\midrule',
        r'\shortstack[l]{Reminder /\\wording} & Representation & Pairs & $e_{\mathrm{self}}$ & $e_{\mathrm{other}}$ & $\Delta_{\mathrm{attr}}$ & \shortstack{Self\\MAE} & \shortstack{Other\\MAE} \\', r'\midrule']
    for i, r in enumerate(static):
        values = [float(r['metrics.' + key + '.estimate']) for key in keys]
        assert math.isclose(values[0] - values[1], values[2], abs_tol=1e-12)
        assert all(r['metrics.' + key + '.n_observations'] == r['complete_pairs'] for key in keys)
        assert int(r['candidate_pairs']) == 24
        if i == 4:
            lines.append(r'\addlinespace')
        lines.append(row([r['reminder'].capitalize() + ' / ' + r['output_instruction'],
            r['template_id'].split('_')[0].capitalize(),
            r['complete_pairs'] + '/' + r['candidate_pairs'], *map(number, values)]))
    lines += [r'\bottomrule', r'\end{tabular*}', r'\par\medskip',
        r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrrr@{}}', r'\toprule',
        r'\multicolumn{7}{l}{\textbf{B. Generated history: scoped reminder and compatible wording, both representations}} \\',
        r'\midrule',
        r'New evidence & Pairs & \shortstack{Native minus\\self replay} & \shortstack{Self minus\\other replay} & \shortstack{Native\\update} & \shortstack{Warranted\\update} & \shortstack{Update\\residual} \\', r'\midrule']
    history = [r for r in read('data/extension/complete_contrasts.csv')
               if r['module'] == 'history_stage2' and r['model'] == 'qwen3-8b-thinking']

    def get(section, contrast, stratum):
        matches = [r for r in history if r['section'] == section and
                   r['contrast'] == contrast and json.loads(r['stratum_json']) == stratum]
        assert len(matches) == 1
        return matches[0]

    for evidence, denominator in [('copy', 48), ('independent', 96)]:
        presentation = [get('history_presentation', contrast, {'evidence_kind': evidence})
                        for contrast in ['history_initial_choice_direction', 'replay_attribution_initial_choice_direction']]
        update = get('history_information', 'update', {'evidence_kind': evidence, 'history_arm': 'native_self'})
        for r in [*presentation, update]:
            assert int(r['complete_valid_sets']) == int(r['candidate_sets']) == denominator
        assert math.isclose(float(update['point']) - float(update['normative_same_sets']),
                            float(update['residual']), abs_tol=1e-12)
        lines.append(row([evidence.capitalize(), f'{denominator}/{denominator}',
                          *[number(r['point']) for r in presentation], number(update['point']),
                          number(update['normative_same_sets']), number(update['residual'])]))
    lines += [r'\bottomrule', r'\end{tabular*}', r'}',
        r'\caption{Qwen3-8B attribution, posterior error, and evidence updating. All estimates use equal family weights and complete pairs. Figure~\ref{fig:extension-diagnosis} adds the static full design bounds.}',
        r'\label{tab:main-results}', r'\end{table*}']
    write('main_results_generated.tex', lines)

    native = read('data/extension/native_configurations.csv')
    assert len(native) == 16
    assert sum(int(r['n_planned']) for r in native) == 2304
    assert sum(int(r['n_valid']) for r in native) == 1736
    lines = [r'% Generated by scripts/build_main_results.py from retained CSVs.',
        r'\begin{table*}[t]', r'\centering', r'{\small\setlength{\tabcolsep}{4pt}',
        r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}llrrrrr@{}}', r'\toprule',
        r'Native thinking & Wording & Token cap & \multicolumn{2}{c}{Positive (copy)} & \multicolumn{2}{c}{Independent} \\',
        r'\cmidrule(lr){4-5}\cmidrule(l){6-7}',
        r' & & & Valid/planned & MAE & Valid/planned & MAE \\', r'\midrule']
    for mode, wording, budget in itertools.product(('on', 'off'), ('compatible', 'restrictive'), (4096, 12288)):
        if (mode, wording, budget) == ('off', 'compatible', 4096):
            lines.append(r'\midrule')
        values = [mode.capitalize(), wording.capitalize(), f'{budget:,}']
        for protocol, denominator in [('positive', 96), ('independent', 192)]:
            matches = [r for r in native if (r['native_mode'], r['output_instruction'], int(r['budget']), r['protocol'])
                       == (mode, wording, budget, protocol)]
            assert len(matches) == 1
            r = matches[0]
            assert int(r['n_planned']) == denominator and r['model'] == 'qwen3-8b-thinking'
            values += [r['n_valid'] + '/' + r['n_planned'], number(r['mae'])]
        lines.append(row(values))
    lines += [r'\bottomrule', r'\end{tabular*}', r'}',
        r'\caption{Qwen3-8B output coverage and error across all eight native configurations. MAE uses valid reports within each configuration with equal family weights. Figure~\ref{fig:extension-native} gives matched contrasts and full design bounds.}',
        r'\label{tab:extension-native-configurations}', r'\end{table*}']
    write('native_results_generated.tex', lines)
    print('Rendered 8 static conditions, 2 history evidence contrasts, and 8 native configurations from exact CSVs.')


if __name__ == '__main__':
    main()
